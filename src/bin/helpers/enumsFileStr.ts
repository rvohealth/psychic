import autogeneratedFileDisclaimer from '../../helpers/autogeneratedFileDisclaimer.js'
import pascalizeFileName from '../../helpers/pascalizeFileName.js'
import OpenapiAppRenderer from '../../openapi-renderer/app.js'
import OpenapiEnumCollector from '../../openapi-renderer/helpers/OpenapiEnumCollector.js'
import PsychicApp from '../../psychic-app/index.js'

/**
 * @internal
 *
 * Builds the client enums file for the OpenAPI spec registered under
 * `openapiName`, by rendering that spec in memory with an
 * `OpenapiEnumCollector` attached and emitting one exported const (plus a
 * derived type) per pg enum the rendered spec actually exposes.
 *
 * Only enums reachable from the selected spec's surface are exported, and
 * each export carries exactly the spec-visible value set (the union of the
 * values the spec's sites render). No database connection is required.
 */
export default function enumsFileStr(openapiName: string = 'default') {
  const psychicApp = PsychicApp.getOrFail()

  const enumCollector = new OpenapiEnumCollector()
  OpenapiAppRenderer._toObject(psychicApp.routesCache, openapiName, { enumCollector })

  const enums = enumCollector.toEnumMap()

  let enumsFileStr = autogeneratedFileDisclaimer()

  Object.keys(enums)
    .sort()
    .forEach(enumName => {
      const exportedTypeName = pascalizeFileName(enumName)
      const exportedConstName = exportedTypeName + 'Values'
      const values = enums[enumName] || []

      enumsFileStr += `\
export const ${exportedConstName} = [
  ${values
    .sort()
    .map(val => `'${val}'`)
    .join(',\n  ')}
] as const
export type ${exportedTypeName} = (typeof ${exportedConstName})[number]

`
    })

  return enumsFileStr
}
